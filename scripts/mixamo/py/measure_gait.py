# (walk-test round 1) Each move's gait, measured from the raw download, headless Blender 5.2.2: its stride (ground
# metres per cycle, on a 1.68 m body) and the share of its cycle where the left foot reaches furthest along the travel
# (its heel strike). Run through scripts/mixamo/gait.mjs, never by hand.
# Args after `--`: --raw <dir> --out <ts file>
import argparse
import os
import statistics
import sys

import bpy
from mathutils import Vector


def args():
    argv = sys.argv[sys.argv.index('--') + 1:]
    p = argparse.ArgumentParser()
    p.add_argument('--raw', required=True)
    p.add_argument('--out', required=True)
    return p.parse_args(argv)


def import_fbx(path):
    before = set(bpy.context.scene.objects)
    bpy.ops.import_scene.fbx(filepath=path, automatic_bone_orientation=False, ignore_leaf_bones=True)
    return [o for o in bpy.context.scene.objects if o not in before]


def bone(arm, short):
    for pb in arm.pose.bones:
        if pb.name.split(':')[-1] == short:
            return pb
    return None


def body_scale(raw):
    """Game metres per world metre: the moves were downloaded on Y Bot, the game's bodies are 1.68 m."""
    objs = import_fbx(os.path.join(raw, 'characters', 'ybot.fbx'))
    zs = [(o.matrix_world @ Vector(c)).z for o in objs if o.type == 'MESH' for c in o.bound_box]
    for o in objs:
        bpy.data.objects.remove(o, do_unlink=True)
    return 1.68 / (max(zs) - min(zs))


def gait(path, k):
    """(stride m, left heel-strike phase 0..1), or None for a move that does not travel."""
    objs = import_fbx(path)
    try:
        arm = [o for o in objs if o.type == 'ARMATURE'][0]
        act = arm.animation_data.action
        f0, f1 = int(act.frame_range[0]), int(act.frame_range[1])
        if f1 - f0 < 4:
            return None
        fps = bpy.context.scene.render.fps / bpy.context.scene.render.fps_base
        sc = bpy.context.scene
        lf = bone(arm, 'LeftToeBase') or bone(arm, 'LeftFoot')
        rf = bone(arm, 'RightToeBase') or bone(arm, 'RightFoot')
        hp = bone(arm, 'Hips')
        if not (lf and rf and hp):
            return None
        rows = []
        for f in range(f0, f1 + 1):
            sc.frame_set(f)
            m = arm.matrix_world
            rows.append(((m @ lf.head).copy(), (m @ rf.head).copy(), (m @ hp.head).copy()))
        zmin = min(min(r[0].z, r[1].z) for r in rows)
        sp, d = [], Vector((0, 0, 0))
        for i in range(1, len(rows)):
            a, b = rows[i - 1], rows[i]
            # the lower foot is the planted one: the body moves over it
            j = 0 if b[0].z < b[1].z else 1
            if (b[j].z - zmin) * k > 0.03:
                continue
            v = ((b[2] - a[2]) - (b[j] - a[j])) * fps
            v.z = 0
            sp.append(v.length)
            d += v
        if not sp or d.length == 0:
            return None
        speed = statistics.median(sp) * k
        if speed < 0.3:
            return None
        d.normalize()
        # the left foot's reach along the travel, from the hips; its furthest is the heel strike
        reach = [(r[0] - r[2]).dot(d) for r in rows[:-1]]
        i = max(range(len(reach)), key=lambda n: reach[n])
        return speed * (f1 - f0) / fps, i / (f1 - f0)
    finally:
        for o in objs:
            bpy.data.objects.remove(o, do_unlink=True)


def main():
    a = args()
    bpy.ops.wm.read_factory_settings(use_empty=True)
    k = body_scale(a.raw)
    moves = os.path.join(a.raw, 'moves')
    rows = []
    for f in sorted(n for n in os.listdir(moves) if n.lower().endswith('.fbx')):
        name = os.path.splitext(f)[0]
        g = gait(os.path.join(moves, f), k)
        if g:
            rows.append(f'  {name}: {{ stride: {g[0]:.3f}, phase: {g[1]:.3f} }},')
            print(f'gait {name}: stride {g[0]:.3f} m, left heel strike at {g[1]:.3f}')
    with open(a.out, 'w', newline='\n') as fh:
        fh.write('// Generated by scripts/mixamo/gait.mjs from the raw Mixamo downloads; do not edit by hand.\n')
        fh.write('/** (walk-test round 1) Each travelling move: its stride (ground metres per cycle, 1.68 m body) and the share\n')
        fh.write(' *  of its cycle where the left foot strikes (the moving clips line up on it). */\n')
        fh.write('export const GAIT: Readonly<Record<string, { stride: number; phase: number }>> = {\n')
        fh.write('\n'.join(rows) + '\n};\n')
    print(f'wrote {a.out}: {len(rows)} moves')


main()
