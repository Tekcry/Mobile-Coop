// (CT prototype G8) Keyed gait clips: hand-written key poses (keys/<clip>.json) baked on Wren's armature in Blender
// (headless, the pinned 5.2.2 through scripts/operators/blender.mjs) and written as a bundled runtime clip
// (src/anim/clips/keyed/<clip>.ts). docs/ct-prototype/G8-PLAN.md.
//   node --import ./scripts/operators/ts-resolve.mjs scripts/anim-keys/build.mjs <clip> [--preview]
// Output: build/anim-keys/<clip>.blend and <clip>.json (not committed), src/anim/clips/keyed/<clip>.ts, and with
// --preview build/anim-keys/<clip>-side.png / <clip>-front.png (8 phases of the keyed pose).
// (anim-skeleton S3) The module source is `clipSource` (exported, so a test checks the emitter without Blender); the
// build runs only when this file is the entry point.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { ROOT, JOINTS_JSON } from '../operators/paths.mjs';
import { runBlender } from '../operators/blender.mjs';

/** The generated clip module for `name` from key_clip.py's JSON `clip` (optional channels only when the bake has them). */
export function clipSource(name, clip) {
  const r = (v) => Math.round(v * 1e5) / 1e5;
  const flat = (k) => clip.samples.flatMap((s) => s[k].map(r));
  // (anim-rig) a clip that keys a wrist frame carries it (8 per frame); without one the line is left out (identity)
  const wrist = clip.samples[0]?.wrist ? `  // wrist L, wrist R local quaternions (x, y, z, w) relative to the forearm
  wrist: [${flat('wrist').join(', ')}],
` : '';
  // (marlow-bays T1a) the optional forearm twist, head and shoulder channels: only when a key sets them
  const opt = (k, note) => (clip.samples[0]?.[k] ? `  // ${note}
  ${k}: [${flat(k).join(', ')}],
` : '');
  const extra = opt('fore', 'forearm twist L, R: local quaternions (x, y, z, w) of the elbow node, about the bone') +
    opt('head', 'head turn: the local quaternion (x, y, z, w) on the neck') +
    opt('sh', 'shoulder L, R: quaternions (x, y, z, w) in the chest frame about the shoulder joint') +
    // (anim-skeleton S3) the clavicle, finger and FK leg channels: only when the key file opts in (src/anim/keyed.ts)
    opt('clav', 'clavicle L, R: local quaternions (x, y, z, w) of the clavicle nodes in the chest frame') +
    opt('fing', 'fingers: hand L then R, thumb .. little, [curl, spread] added to the grip shape') +
    opt('leg', 'legs L then R: hip quaternion (pelvis), knee flex (rad), ankle quaternion (knee), toe (rad), FK weight') +
    // (anim-skeleton S4) the per-key leg deltas on the planner's IK legs: only when a key sets one
    // (tuner-clarity S2) 9 a side: the ankle yaw and the shin twist appended
    opt('legd', 'leg deltas L then R (9 each): hip pitch, yaw, roll, knee, ankle pitch, roll, toe, ankle yaw, shin twist (rad, rig frame) on the IK leg');
  return `// GENERATED by scripts/anim-keys/build.mjs from scripts/anim-keys/keys/${name}.json (Blender ${clip.blender}, ${clip.operator}
// ${clip.height} m). Do not edit: change the keys and rebuild. Body frame at 1.75 m (x right, y up, z forward), one row per frame.
import { keyedClip } from '../../keyed';

export const KEYED_${name.toUpperCase()} = keyedClip({
  name: '${name}',
  frames: ${clip.frames},
  duty: ${clip.duty},
  liftH: ${clip.liftH},
  kneeOut: ${clip.kneeOut},
  half: ${r(clip.half)},
  // pelvis offset from rest (x, y, z)
  pel: [${flat('pel').join(', ')}],
  // local quaternions (x, y, z, w) of pelvis, spine, chest, neck
  q: [${flat('q').join(', ')}],
  // elbow L, wrist L, elbow R, wrist R from the shoulder joint, chest frame
  arm: [${flat('arm').join(', ')}],
${wrist}${extra}});
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const [name = 'walk', ...flags] = process.argv.slice(2);
  const preview = flags.includes('--preview');
  const OUT = path.join(ROOT, 'build', 'anim-keys');
  mkdirSync(OUT, { recursive: true });
  if (!existsSync(JOINTS_JSON)) {
    const { exportJoints } = await import('../operators/export-joints.mjs');
    exportJoints();
  }
  const keys = path.join(ROOT, 'scripts', 'anim-keys', 'keys', `${name}.json`);
  const json = path.join(OUT, `${name}.json`);
  const prevDir = path.join(OUT, 'preview');
  runBlender(path.join('..', '..', 'anim-keys', 'py', 'key_clip.py'), [
    '--joints', JOINTS_JSON, '--operator', 'wren', '--keys', keys, '--out', json, '--blend', path.join(OUT, `${name}.blend`),
    ...(preview ? ['--preview', prevDir] : []),
  ]);
  const clip = JSON.parse(readFileSync(json, 'utf8'));
  const src = clipSource(name, clip);
  const tsOut = path.join(ROOT, 'src', 'anim', 'clips', 'keyed', `${name}.ts`);
  mkdirSync(path.dirname(tsOut), { recursive: true });
  writeFileSync(tsOut, src);
  console.log(`anim-keys: ${name} -> ${path.relative(ROOT, tsOut)}`);
  // (anim-skeleton S3b) a key file with `checkFrames` gets its frame proof (Blender-evaluated positions) as a test fixture
  if (clip.check) {
    const chk = path.join(ROOT, 'tests', 'fixtures', `keyed-check-${name}.json`);
    const round = (_k, v) => (typeof v === 'number' ? Math.round(v * 1e6) / 1e6 : v);
    writeFileSync(chk, JSON.stringify({ name, blender: clip.blender, check: clip.check }, round) + '\n');
    console.log(`anim-keys: ${name} frame proof -> ${path.relative(ROOT, chk)}`);
  }
  if (preview) {
    const FF = process.env.FFMPEG ?? 'C:/Users/Micha/AppData/Local/Microsoft/WinGet/Packages/Gyan.FFmpeg_Microsoft.Winget.Source_8wekyb3d8bbwe/ffmpeg-9.0.2-full_build/bin/ffmpeg.exe';
    for (const view of ['side', 'front']) {
      const inputs = [];
      for (let i = 0; i < 8; i++) inputs.push('-i', path.join(prevDir, `${name}-${view}-${i}.png`));
      const lab = Array.from({ length: 8 }, (_, i) => `[${i}]drawtext=fontfile='C\\:/Windows/Fonts/consola.ttf':text='keyed ${name} ph ${(i / 8).toFixed(3)}':x=4:y=4:fontsize=14:fontcolor=black[v${i}]`).join(';');
      const res = spawnSync(FF, ['-v', 'error', '-y', ...inputs, '-filter_complex', `${lab};${Array.from({ length: 8 }, (_, i) => `[v${i}]`).join('')}hstack=inputs=8`, path.join(OUT, `${name}-${view}.png`)], { windowsHide: true, encoding: 'utf8' });
      console.log(`anim-keys: preview ${view}`, res.status === 0 ? path.join(OUT, `${name}-${view}.png`) : res.stderr);
    }
  }
}
