#!/usr/bin/env node
/**
 * rig-pose-fix S1: builds the tables of `src/player/playerVolumes.ts` from the sweep written by
 * `tests/playerVolumesSweep.test.ts` (one TSV line per knot scenario: table, row, base row, the rig's mean capsule-local
 * offsets of the pelvis, chest, neck and head). Each row is the mean of its scenarios (the aimed walks: the four
 * directions) minus its base row when it names one (the move tables over the still stance, the kneel over the crouched
 * stance, the slide over the still wall stance). Values in metres for Wren, 1 mm rounding.
 *
 *   PLAYER_BODY_SWEEP=1 PLAYER_BODY_OUT=pb.tsv npx vitest run tests/playerVolumesSweep.test.ts
 *   node scripts/player-body-fit.mjs pb.tsv --write
 *
 * `--write` replaces the block between the `<player-body-fit>` markers of `src/player/playerVolumes.ts`; without it the
 * block is printed. The knots below must match `tests/helpers/playerBodyHarness.ts` (`sweepScenarios`).
 */
import { readFileSync, writeFileSync } from 'node:fs';

const args = process.argv.slice(2);
const WRITE = args.includes('--write');
const file = args.find((a) => a !== '--write');
if (!file) {
  console.error('usage: node scripts/player-body-fit.mjs <sweep.tsv> [--write]');
  process.exit(1);
}
const [hdr, ...lines] = readFileSync(file, 'utf8').trim().split(/\r?\n/);
const cols = hdr.split('\t');
const V0 = cols.indexOf('pelvisX');
const raw = new Map();
for (const l of lines) {
  const v = l.split('\t');
  const key = `${v[1]}:${v[2]}`;
  const vals = v.slice(V0, V0 + 12).map(Number);
  const e = raw.get(key) ?? { n: 0, sum: new Array(12).fill(0), base: v[3] };
  e.n++;
  for (let k = 0; k < 12; k++) e.sum[k] += vals[k];
  raw.set(key, e);
}
const mean = (key) => {
  const e = raw.get(key);
  if (!e) throw new Error(`missing ${key}`);
  return e.sum.map((s) => s / e.n);
};
const row = (key) => {
  const m = mean(key);
  const b = raw.get(key).base;
  if (b === '-') return m;
  const bm = mean(b);
  return m.map((v, k) => v - bm[k]);
};
const r3 = (v) => {
  const x = Math.round(v * 1000) / 1000;
  return Object.is(x, -0) ? 0 : x;
};
const table = (tab, n) => {
  const out = [];
  for (let i = 0; i < n; i++) out.push(...row(`${tab}:${i}`).map(r3));
  return out;
};
const fmt = (a) => {
  const rows = [];
  for (let i = 0; i < a.length; i += 12) rows.push(`  ${a.slice(i, i + 12).join(', ')},`);
  return `[\n${rows.join('\n')}\n]`;
};

const CYCLIC = ['hang', 'climb', 'pipeClimb', 'crawl', 'rappel', 'split', 'brace', 'pipeLegs', 'pipeInv'];
const PHASED = ['vault', 'mantle', 'step', 'drop', 'hop', 'roll', 'windowVault', 'climbUp', 'ventDrop', 'crawlOut', 'wallKick'];
const T = (name, tab, n) => `const ${name}: readonly number[] = ${fmt(table(tab, n))};`;
const trav = [...CYCLIC.map((k) => `  ${k}: ${fmt(table(`TRAV_${k}`, 1)).replace(/\n/g, '\n  ')},`), ...PHASED.map((k) => `  ${k}: ${fmt(table(`TRAV_${k}`, 9)).replace(/\n/g, '\n  ')},`)];
const block = `// <player-body-fit>
// generated by scripts/player-body-fit.mjs from the mocap-ON sweep (rows of 12: pelvis, chest, neck, head x side, up,
// forward; m, Wren)
const FIT_C5 = [0, 0.25, 0.5, 0.75, 1];
const FIT_C3 = [0, 0.5, 1];
const FIT_CW = [0, 0.35, 0.6, 0.85, 1];
const FIT_P5 = [-0.5, -0.25, 0, 0.25, 0.5];
const FIT_PE3 = [0, 0.5, 1];
const FIT_T9 = [0, 0.125, 0.25, 0.375, 0.5, 0.625, 0.75, 0.875, 1];
const SP_STAND = [0.75, 1.4, 2.1, 3, 4];
const SP_CROUCH = [0.85, 1.3, 1.7, 2.15, 2.6];
const SP_AIM = [0.5, 1, 1.4];
const SP_WALL0 = [0.2, 0.39];
const SP_WALL1 = [0.25, 0.55];
/** Free, still, over the crouch blend (FIT_C5): holstered, drawn at low ready. */
${T('STILL_H', 'STILL_H', 5)}
${T('STILL_L', 'STILL_L', 5)}
/** Free, still, raised: crouch (FIT_C3) x aim pitch (FIT_P5). */
${T('STILL_A', 'STILL_A', 15)}
/** The kneel over the crouched stance: holstered, low ready, raised per pitch (FIT_P5). */
${T('KNEEL_H', 'KNEEL_H', 1)}
${T('KNEEL_L', 'KNEEL_L', 1)}
${T('KNEEL_A', 'KNEEL_A', 5)}
/** Free, moving, over the still stance, per speed knot: holstered / low ready standing (SP_STAND) and crouched
 *  (SP_CROUCH), raised standing / crouched (SP_AIM): ahead and back (AF), left and right (AS). */
${T('MOVE_H0', 'MOVE_H0', 5)}
${T('MOVE_H1', 'MOVE_H1', 5)}
${T('MOVE_L0', 'MOVE_L0', 5)}
${T('MOVE_L1', 'MOVE_L1', 5)}
${T('MOVE_AF0', 'MOVE_AF0', 3)}
${T('MOVE_AS0', 'MOVE_AS0', 3)}
${T('MOVE_AF1', 'MOVE_AF1', 3)}
${T('MOVE_AS1', 'MOVE_AS1', 3)}
/** Back to a wall (stance side right; mirrored for the left): crouch (FIT_CW: the side-on turn eases in over 0.35-0.85) x peek (FIT_PE3), holstered / drawn. */
${T('WALL_H', 'WALL_H', 15)}
${T('WALL_D', 'WALL_D', 15)}
/** The slide over the still wall stance (standing SP_WALL0, crouched SP_WALL1). */
${T('SLIDE_0', 'SLIDE_0', 2)}
${T('SLIDE_1', 'SLIDE_1', 2)}
/** Cyclic families: the cycle's mean (12); phased families: over \`FIT_T9\` (108). */
const TRAV: Partial<Record<TraverseKind, readonly number[]>> = {
${trav.join('\n')}
};
// </player-body-fit>`;

if (!WRITE) {
  console.log(block);
  process.exit(0);
}
const path = new URL('../src/player/playerVolumes.ts', import.meta.url);
const src = readFileSync(path, 'utf8');
const a = src.indexOf('// <player-body-fit>');
const b = src.indexOf('// </player-body-fit>');
if (a < 0 || b < 0) throw new Error('markers not found');
writeFileSync(path, src.slice(0, a) + block + src.slice(b + '// </player-body-fit>'.length));
console.error('wrote src/player/playerVolumes.ts');
