/**
 * The section's interactables (K4) from the layout and, when given, its sector: switches, boards, laser panels, alarms
 * (section-tagged), pickups, security desks, and the sector's keypads, pair-gate key switches, intel boards, objective
 * and crate.
 */
export function collectItems(lay: MapLayout, section: number, sector?: SectorDef): DressContext['items'] {
  const out: { x: number; y: number; z: number; what: string }[] = [];
  const v = (p: { x: number; y: number; z: number }, what: string): void => {
    out.push({ x: p.x, y: p.y, z: p.z, what });
  };
  for (const s of lay.switches ?? []) if (s.section === section) v(s.pos, 'switch');
  for (const s of lay.boards ?? []) if (s.section === section) v(s.pos, 'board');
  for (const s of lay.alarms ?? []) if (s.section === section) v(s.pos, 'alarm');
  for (const s of lay.laserPanels ?? []) if (s.section === section) out.push({ x: s.x, y: s.y, z: s.z, what: `laser panel ${s.id}` });
  for (const s of lay.pickups) v(s.pos, 'pickup');
  for (const d of lay.security?.desks ?? []) if (d.section === section) out.push({ x: d.at[0], y: (d.y ?? 0) + 1.0, z: d.at[1], what: `desk ${d.id}` });
  if (sector) {
    const o = sector.objective;
    out.push({ x: o.x, y: o.y, z: o.z, what: `objective ${o.label}` });
    for (const k of sector.keypads ?? []) out.push({ x: k.at[0], y: 1.2, z: k.at[1], what: `keypad ${k.code}` });
    for (const g of sector.pairGates ?? []) for (const s of [g.a, g.b]) out.push({ x: s.at[0], y: (s.y ?? 0) + 1.2, z: s.at[1], what: 'pair key switch' });
    for (const i of sector.intel ?? []) if (i.kind === 'board') out.push({ x: i.at[0], y: i.at[1], z: i.at[2], what: `intel ${i.grants}` });
    if (sector.crate) out.push({ x: sector.crate.at[0], y: sector.crate.at[1], z: sector.crate.at[2], what: 'weapons crate' });
  }
  return out;
}

