const ALL = 1e6;

function bandOf(y: number | undefined): [number, number] {
  return y === undefined ? [-ALL, ALL] : [y - KEEP.band0, y + KEEP.band1];
}

function samples(pts: readonly (readonly [number, number, number])[]): number[] {
  const out: number[] = [];
  for (let i = 0; i < pts.length; i++) {
    const a = pts[i]!;
    if (i === pts.length - 1 || pts.length === 1) {
      out.push(a[0], a[1], a[2]);
      continue;
    }
    const b = pts[i + 1]!;
    const n = Math.max(1, Math.ceil(Math.sqrt((b[0] - a[0]) ** 2 + (b[1] - a[1]) ** 2 + (b[2] - a[2]) ** 2) / 0.15));
    for (let k = 0; k < n; k++) out.push(a[0] + ((b[0] - a[0]) * k) / n, a[1] + ((b[1] - a[1]) * k) / n, a[2] + ((b[2] - a[2]) * k) / n);
  }
  return out;
}

/** The plan opening of a door: hinge -> hinge + width along the closed leaf, and its normal. */
export function doorLine(d: Door): { ax: number; az: number; bx: number; bz: number; nx: number; nz: number; cx: number; cz: number } {
  const tx = Math.sin(d.yaw);
  const tz = Math.cos(d.yaw);
  const bx = d.hinge.x + tx * d.width;
  const bz = d.hinge.z + tz * d.width;
  return { ax: d.hinge.x, az: d.hinge.z, bx, bz, nx: tz, nz: -tx, cx: (d.hinge.x + bx) / 2, cz: (d.hinge.z + bz) / 2 };
}

/** A co-op lip's plan segment (ART-KIT L8: a lip with an x-normal runs along z at `x`, z0..z1; one with a z-normal runs
 *  along x over its top's x range at z0). */
export function lipLine(l: CoopLip): { ax: number; az: number; bx: number; bz: number } {
  if (Math.abs(l.lip.n.x) >= Math.abs(l.lip.n.z)) return { ax: l.lip.x, az: l.lip.z0, bx: l.lip.x, bz: l.lip.z1 };
  return { ax: l.top.x0, az: l.lip.z0, bx: l.top.x1, bz: l.lip.z0 };
}

export function buildKeepouts(ctx: DressContext): Keepouts {
  const nBoxes = ctx.boxes.length;
  // the section's bounds: its rooms, 6 m round
  let x0 = Infinity;
  let z0 = Infinity;
  let x1 = -Infinity;
  let z1 = -Infinity;
  for (const r of ctx.rooms) {
    x0 = Math.min(x0, r.minX);
    z0 = Math.min(z0, r.minZ);
    x1 = Math.max(x1, r.maxX);
    z1 = Math.max(z1, r.maxZ);
  }
  if (!ctx.rooms.length) x0 = z0 = x1 = z1 = 0;
  x0 -= 6;
  z0 -= 6;
  x1 += 6;
  z1 += 6;
  const inB = (x: number, z: number, m = 0): boolean => x >= x0 - m && x <= x1 + m && z >= z0 - m && z <= z1 + m;
  // (artpol, art-kit P3) a segment that meets the bounds grown by m: a long leg that crosses the section with both ends
  // outside it is kept (an end test alone dropped it)
  const segInB = (ax: number, az: number, bx: number, bz: number, m: number): boolean => segRectDist(planRect((x0 + x1) / 2, (z0 + z1) / 2, (x1 - x0) / 2 + m, (z1 - z0) / 2 + m, 0), ax, az, bx, bz) <= 0;
  const caps: PlanCap[] = [];
  const cap = (ax: number, az: number, bx: number, bz: number, ya: number | undefined, yb: number | undefined, r: number, rule: string, what: string): void => {
    if (!segInB(ax, az, bx, bz, r + 4)) return;
    const [a0, a1] = bandOf(ya);
    const [b0, b1] = bandOf(yb);
    caps.push({ ax, az, bx, bz, y0: Math.min(a0, b0), y1: Math.max(a1, b1), r, rule, what });
  };
  const sec = ctx.sector;
  // K1 player route legs (climbs included)
  for (const rt of sec.routes) {
    for (let i = 0; i + 1 < rt.pts.length; i++) {
      const a = rt.pts[i]!;
      const b = rt.pts[i + 1]!;
      cap(a[0], a[1], b[0], b[1], a[2] ?? 0, b[2] ?? 0, KEEP.route, 'K1', `route ${rt.name} leg ${i}`);
    }
  }
  // K2 guard patrol legs (slot -> route -> slot), reinforce points, entries' run-ins, stage-action routes
  sec.guards.forEach((g, gi) => {
    const pts: [number, number][] = [[g.x, g.z], ...(g.route ?? []), [g.x, g.z]];
    for (let i = 0; i + 1 < pts.length; i++) cap(pts[i]![0], pts[i]![1], pts[i + 1]![0], pts[i + 1]![1], g.y ?? 0, g.y ?? 0, KEEP.patrol, 'K2', `guard ${gi} leg ${i}`);
    // K5 takedown spots
    cap(g.takedownSpot[0], g.takedownSpot[1], g.takedownSpot[0], g.takedownSpot[1], g.y ?? 0, g.y ?? 0, KEEP.takedown, 'K5', `guard ${gi} takedown spot`);
  });
  for (const [x, z] of sec.reinforce) cap(x, z, x, z, undefined, undefined, KEEP.patrol, 'K2', 'reinforce point');
  // K2 response-team sweep points (gear / sweep lane: ground storey, ART-PLAN 4.3 K2; art-join)
  for (const [x, z] of sec.sweep ?? []) cap(x, z, x, z, 0, 0, KEEP.patrol, 'K2', 'sweep point');
  for (const e of sec.entries ?? []) {
    const pts: [number, number][] = [e.at, ...(e.route ?? [])];
    for (let i = 0; i + 1 < pts.length; i++) cap(pts[i]![0], pts[i]![1], pts[i + 1]![0], pts[i + 1]![1], e.y, e.y, KEEP.patrol, 'K2', `entry run-in ${i}`);
    cap(e.at[0], e.at[1], e.at[0], e.at[1], e.y, e.y, KEEP.patrol, 'K2', 'entry');
  }
  for (const s of sec.stageActions ?? []) {
    const r = s.responseRoute ?? [];
    for (let i = 0; i + 1 < r.length; i++) cap(r[i]![0], r[i]![1], r[i + 1]![0], r[i + 1]![1], undefined, undefined, KEEP.patrol, 'K2', `stage ${s.stage} response leg ${i}`);
  }
  // K4 items
  for (const it of ctx.items) cap(it.x, it.z, it.x, it.z, it.y - 1.2, it.y - 1.2, KEEP.item, 'K4', it.what);
  // K6 hide spots, spawns, nav seeds, checkpoints, the extract zone
  for (const h of ctx.hides) cap(h.x, h.z, h.x, h.z, h.y, h.y, KEEP.hide, 'K6', 'hide / spawn / seed');
  cap(sec.start.x, sec.start.z, sec.start.x, sec.start.z, sec.start.y, sec.start.y, KEEP.hide, 'K6', 'section start');
  if (sec.connector) {
    const c = sec.connector.checkpoint;
    cap(c.x, c.z, c.x, c.z, c.y, c.y, KEEP.hide, 'K6', 'checkpoint');
  }
  const zones: Zone[] = [];
  const wallZones: Zone[] = [];
  if (sec.extract) {
    const b = sec.extract.box;
    const fy = sec.extract.floorY ?? 0;
    zones.push({ r: planRect((b[0] + b[2]) / 2, (b[1] + b[3]) / 2, Math.abs(b[2] - b[0]) / 2, Math.abs(b[3] - b[1]) / 2, 0), y0: fy - KEEP.band0, y1: fy + KEEP.band1, rule: 'K6', what: 'extract zone' });
  }
  // K3 doors (and K13 the escape doors: a side with no room, or an outdoor room)
  for (const d of ctx.doors) {
    const l = doorLine(d);
    if (!inB(l.cx, l.cz, 4)) continue;
    // planRect's local x is (cos yaw', -sin yaw'): the opening's tangent (tx, tz) gives yaw' = atan2(-tz, tx)
    const ry = Math.atan2(-(l.bz - l.az), l.bx - l.ax);
    const y0 = d.hinge.y - KEEP.band0;
    const y1 = d.hinge.y + KEEP.band1;
    zones.push({ r: planRect(l.cx, l.cz, d.width / 2 + KEEP.doorWide, KEEP.doorDeep + 0.2, ry), y0, y1, rule: 'K3', what: `door ${d.id}`, door: d.id });
    caps.push({ ax: d.hinge.x, az: d.hinge.z, bx: d.hinge.x, bz: d.hinge.z, y0, y1, r: d.width + KEEP.doorSwing, rule: 'K3', what: `door ${d.id} swing`, door: d.id });
    wallZones.push({ r: planRect(l.cx, l.cz, d.width / 2 + KEEP.doorWall, 0.45, ry), y0: d.hinge.y - 0.1, y1: d.hinge.y + d.height + KEEP.doorWall, rule: 'K3', what: `door ${d.id} opening`, door: d.id });
    const outA = roomAt(ctx.rooms, l.cx + l.nx * 1.5, l.cz + l.nz * 1.5, d.hinge.y);
    const outB = roomAt(ctx.rooms, l.cx - l.nx * 1.5, l.cz - l.nz * 1.5, d.hinge.y);
    const out = (i: number): boolean => i < 0 || isOutdoor(ctx.tags[ctx.rooms[i]!.id]);
    if (out(outA) !== out(outB)) zones.push({ r: planRect(l.cx, l.cz, d.width / 2 + 0.1, KEEP.escape + 0.2, ry), y0, y1, rule: 'K13', what: `escape door ${d.id}`, door: d.id });
  }
  // K4 on the wall: no wall piece within 0.6 of an item
  const wallPts = ctx.items.map((it) => ({ x: it.x, y: it.y, z: it.z, r: KEEP.itemWall, rule: 'K4', what: it.what }));
  // K9 lasers, K10 lamps, K11 anchors: 3D tubes / spheres (floor, wall, ceiling radii)
  const tubes: Tube[] = [];
  const tube = (pts: (readonly [number, number, number])[], floor: number, wall: number, ceil: number, rule: string, what: string): void => {
    let near = pts.length === 1 && inB(pts[0]![0], pts[0]![2], 4);
    for (let i = 0; !near && i + 1 < pts.length; i++) near = segInB(pts[i]![0], pts[i]![2], pts[i + 1]![0], pts[i + 1]![2], 4);
    if (!near) return;
    const sp = samples(pts);
    const bb: [number, number, number, number, number, number] = [Infinity, Infinity, Infinity, -Infinity, -Infinity, -Infinity];
    for (let i = 0; i < sp.length; i += 3) {
      for (let a = 0; a < 3; a++) {
        if (sp[i + a]! < bb[a]!) bb[a] = sp[i + a]!;
        if (sp[i + a]! > bb[a + 3]!) bb[a + 3] = sp[i + a]!;
      }
    }
    tubes.push({ pts: sp, bb, floor, wall, ceil, rule, what });
  };
  for (const l of ctx.lasers) for (const y of l.ys) tube([[l.x1, (l.floorY ?? 0) + y, l.z1], [l.x2, (l.floorY ?? 0) + y, l.z2]], KEEP.laser, KEEP.laser, KEEP.laser, 'K9', `laser ${l.id}`);
  for (const p of ctx.lamps) tube([[p.x, p.y, p.z]], KEEP.lamp, KEEP.lamp, KEEP.lamp, 'K10', 'lamp');
  const an = ctx.anchors;
  const p3 = (p: { x: number; y: number; z: number }): [number, number, number] => [p.x, p.y, p.z];
  const anchorTube = (pts: [number, number, number][], what: string): void => {
    tube(pts, KEEP.anchorFloor, KEEP.anchorWall, KEEP.anchorCeil, 'K11', what);
    const a = pts[0]!;
    const b = pts[pts.length - 1]!;
    cap(a[0], a[2], a[0], a[2], a[1], a[1], KEEP.anchorEnd, 'K11', `${what} end`);
    cap(b[0], b[2], b[0], b[2], b[1], b[1], KEEP.anchorEnd, 'K11', `${what} end`);
  };
  for (const l of an.ladders) anchorTube([p3(l.base), p3(l.top)], `ladder ${l.id}`);
  for (const p of an.pipesV) anchorTube([p3(p.base), p3(p.top)], `pipe ${p.id}`);
  for (const p of an.pipesH) anchorTube([p3(p.a), p3(p.b)], `pipe ${p.id}`);
  for (const d of an.ducts) anchorTube(d.path.map(p3), `duct ${d.id}`);
  for (const z of an.ziplines) anchorTube([p3(z.a), p3(z.b)], `zipline ${z.id}`);
  for (const r of an.rappels) anchorTube([p3(r.top), [r.top.x + r.nx * 0.3, r.top.y - r.length, r.top.z + r.nz * 0.3]], `rope ${r.id}`);
  for (const w of ctx.windows) {
    const tx = Math.cos(w.yaw);
    const tz = -Math.sin(w.yaw);
    anchorTube(
      [
        [w.c.x - (tx * w.w) / 2, w.sillHeight, w.c.z - (tz * w.w) / 2],
        [w.c.x + (tx * w.w) / 2, w.sillHeight, w.c.z + (tz * w.w) / 2],
      ],
      `window ${w.id}`,
    );
  }
  for (const s of ctx.splits ?? []) anchorTube([p3(s.a), p3(s.b)], 'split gap');
  // K7 co-op lips
  const lips: LipKO[] = ctx.lips
    .filter((l) => l.section === ctx.section)
    .map((l) => {
      const s = lipLine(l);
      const len = hyp2(s.bx - s.ax, s.bz - s.az);
      const ry = len > 1e-6 ? Math.atan2(-(s.bz - s.az), s.bx - s.ax) : Math.atan2(l.lip.n.x, l.lip.n.z);
      const half = len / 2;
      return {
        id: l.id,
        ...s,
        nx: l.lip.n.x,
        nz: l.lip.n.z,
        y: l.lip.y,
        floor: l.boost.floor,
        prism: { r: planRect((s.ax + s.bx) / 2, (s.az + s.bz) / 2, half + 0.3, KEEP.lipOut, ry), y0: l.lip.y + KEEP.lipPrism[0], y1: l.lip.y + KEEP.lipPrism[1], rule: 'K7', what: `lip ${l.id} headroom` },
      };
    });
  const glass: number[] = [];
  for (let i = 0; i < nBoxes; i++) {
    const b = ctx.boxes[i]!;
    if (b.glass && inB(b.c[0], b.c[2], 2)) glass.push(i);
  }
  const grid = new BoxGrid(ctx.boxes, nBoxes, x0 - 10, z0 - 10, x1 + 10, z1 + 10);
  const rays = cameraRays(ctx, grid, nBoxes);
  return { caps, zones, wallZones, wallPts, tubes, lips, rays, glass, nBoxes, grid, bounds: { x0, z0, x1, z1 } };
}

/** K8: the rays the greybox leaves clear, per camera of the section (5 deg sweep steps, a 1 m floor grid, 3 heights). */
function cameraRays(ctx: DressContext, grid: BoxGrid, nBoxes: number): CamRay[] {
  const out: CamRay[] = [];
  const DEG = Math.PI / 180;
  for (const c of ctx.cameras) {
    if (c.section !== undefined && c.section !== ctx.section) continue;
    const fy = ctx.levels[c.level] ?? 0;
    const cx = c.at[0];
    const cy = fy + c.y;
    const cz = c.at[1];
    const pitch = camPitch(c);
    const range = camRange(c);
    const yaws: number[] = [];
    if (c.sweep) {
      const a = Math.min(c.sweep[0], c.sweep[1]);
      const b = Math.max(c.sweep[0], c.sweep[1]);
      for (let t = a; t < b + 1e-6; t += KEEP.camYawStep) yaws.push(t * DEG);
      if (yaws[yaws.length - 1]! < b * DEG - 1e-6) yaws.push(b * DEG);
    } else yaws.push(sweepYaw(c, 0));
    const occ = grid.query(cx - range, cz - range, cx + range, cz + range).filter((i) => {
      const b = ctx.boxes[i]!;
      return i < nBoxes && b.collide && b.glass !== 'clear';
    });
    const obbs = occ.map((i) => boxObb(ctx.boxes[i]!));
    for (let gx = Math.ceil((cx - range) / KEEP.camStep) * KEEP.camStep; gx <= cx + range; gx += KEEP.camStep) {
      for (let gz = Math.ceil((cz - range) / KEEP.camStep) * KEEP.camStep; gz <= cz + range; gz += KEEP.camStep) {
        for (const h of KEEP.camHeights) {
          const py = fy + h;
          if (!yaws.some((yw) => inFrame(yw, cx, cy, cz, gx, py, gz, pitch, range))) continue;
          // clear in the greybox? (a box under the lens' own housing is skipped: the ray starts 0.2 out)
          const d = hyp2(gx - cx, gz - cz);
          const ox = d > 1e-6 ? cx + ((gx - cx) / d) * 0.2 : cx;
          const oz = d > 1e-6 ? cz + ((gz - cz) / d) * 0.2 : cz;
          let blockedRay = false;
          for (const o of obbs) {
            if (segHitsObb(o, ox, cy, oz, gx, py, gz, 0.005)) {
              blockedRay = true;
              break;
            }
          }
          if (blockedRay) continue;
          out.push({ ax: ox, ay: cy, az: oz, bx: gx, by: py, bz: gz, lo: [Math.min(ox, gx), Math.min(cy, py), Math.min(oz, gz)], hi: [Math.max(ox, gx), Math.max(cy, py), Math.max(oz, gz)], cam: c.id });
        }
      }
    }
  }
  return out;
}

