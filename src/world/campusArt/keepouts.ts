/** Where a piece mounts by its frame: a hull wholly below its origin is a ceiling piece; a hung or z0 = 0 piece a wall
 *  piece; the rest floor pieces. */
export function mountOf(cat: PropCatalogue, prop: string): Mount {
  const h = pieceHull(cat, prop);
  if (h.hi[1] <= 1e-6) return 'ceiling';
  const f = cat.footprint[prop];
  // a hung piece is a wall piece with its back on the face (z0 = 0), else it hangs from the ceiling (duct runs, trays)
  if (cat.hung.includes(prop)) return f && Math.abs(f[1]) < 1e-6 ? 'wall' : 'ceiling';
  if (f && Math.abs(f[1]) < 1e-6 && h.lo[1] > 0.05) return 'wall';
  if (f && Math.abs(f[1]) < 1e-6 && (h.hi[2] - h.lo[2]) <= 0.2) return 'wall';
  return 'floor-free';
}

interface Shape {
  obb: Obb3;
  plan: PlanRect;
  y0: number;
  y1: number;
  /** A gameplay box (solid / see) rather than the drawn hull. */
  box: boolean;
  solid: boolean;
}

const fromWorldObb = (w: WorldObb): Shape => ({
  obb: obbOf([w.cx, (w.y0 + w.y1) / 2, w.cz], [w.hx * 2, Math.max(1e-3, w.y1 - w.y0), w.hz * 2], w.yaw),
  plan: planRect(w.cx, w.cz, w.hx, w.hz, w.yaw),
  y0: w.y0,
  y1: w.y1,
  box: false,
  solid: false,
});

/** The placement's hull and (solid / see) boxes as world shapes. */
export function shapesOf(cat: PropCatalogue, p: ArtPlacement): Shape[] {
  const out: Shape[] = [fromWorldObb(hullObb(cat, p))];
  if (writesBoxes(p)) {
    for (const w of artBoxes(cat, p) ?? []) {
      out.push({ obb: obbOf(w.c, w.s, w.yaw), plan: planRect(w.c[0], w.c[2], w.s[0] / 2, w.s[2] / 2, w.yaw), y0: w.c[1] - w.s[1] / 2, y1: w.c[1] + w.s[1] / 2, box: true, solid: w.visible });
    }
  }
  return out;
}

/** The gap behind a piece's back face (its hull's local z0) to the first greybox box, searched 0.3 m (Infinity: none);
 *  `glass` when that box is glass; `back` the back face's local z (scaled). */
export function backGap(k: Keepouts, boxes: readonly BoxPiece[], cat: PropCatalogue, p: ArtPlacement): { gap: number; glass: boolean; back: number } {
  const h = pieceHull(cat, p.prop);
  const sy = p.s?.[1] ?? 1;
  const back = Math.min(h.lo[2], h.hi[2]) * (p.s?.[2] ?? 1);
  const y = p.y + ((h.lo[1] + h.hi[1]) / 2) * sy;
  const nx = -Math.sin(p.yaw);
  const nz = -Math.cos(p.yaw);
  const bx = p.x - nx * back;
  const bz = p.z - nz * back;
  const near = k.grid.query(bx - 0.5, bz - 0.5, bx + 0.5, bz + 0.5);
  // (artpol, load time) only the collide boxes within reach of the 0.3 m search (every sample is within 0.15 of its
  // middle), in grid order as before
  const obbs: { o: Obb3; glass: boolean }[] = [];
  for (const i of near) {
    const b = boxes[i]!;
    if (!b.collide) continue;
    const o = boxObb(b);
    if (pointObbDist(o, bx + nx * 0.15, y, bz + nz * 0.15) > 0.151) continue;
    obbs.push({ o, glass: !!b.glass });
  }
  for (let d = 0; d <= 0.3 + 1e-9; d += 0.005) {
    const x = bx + nx * d;
    const z = bz + nz * d;
    for (const o of obbs) if (pointObbDist(o.o, x, y, z) < 1e-4) return { gap: d, glass: o.glass, back };
  }
  return { gap: Infinity, glass: false, back };
}

/** The floor under a placement: the highest collide box top over its origin at or below its bottom + 0.3. */
export function floorUnder(k: Keepouts, boxes: readonly BoxPiece[], cat: PropCatalogue, p: ArtPlacement): number {
  const h = pieceHull(cat, p.prop);
  const bottom = p.y + Math.min(h.lo[1], h.hi[1]) * (p.s?.[1] ?? 1);
  let best = -Infinity;
  for (const i of k.grid.query(p.x, p.z, p.x, p.z)) {
    const b = boxes[i]!;
    if (!b.collide || pointRectDist(boxPlan(b).r, p.x, p.z) > 0) continue;
    const top = boxPlan(b).y1;
    if (top <= bottom + 0.3 && top > best) best = top;
  }
  return best;
}

/** (artnext A6) A decal piece by shape: a visual piece that writes no box, not a ceiling piece, its scaled hull under
 *  `DECAL_H` tall (the floor tile grid). `isDecal` adds the floor. */
export function decalPiece(cat: PropCatalogue, p: ArtPlacement): boolean {
  if (p.cls !== 'visual' || mountOf(cat, p.prop) === 'ceiling') return false;
  const h = pieceHull(cat, p.prop);
  return Math.abs(h.hi[1] - h.lo[1]) * (p.s?.[1] ?? 1) < DECAL_H;
}

/** (artnext A6) A floor decal: a `decalPiece` whose hull bottom is within `DECAL_H` of the floor under it. Exempt from
 *  K1-K6 and K13 (the floor keepouts the nav gate protects: it is walked over) and from the greybox overlap. */
export function isDecal(k: Keepouts, boxes: readonly BoxPiece[], cat: PropCatalogue, p: ArtPlacement): boolean {
  if (!decalPiece(cat, p)) return false;
  const h = pieceHull(cat, p.prop);
  const bottom = p.y + Math.min(h.lo[1], h.hi[1]) * (p.s?.[1] ?? 1);
  return Math.abs(bottom - floorUnder(k, boxes, cat, p)) <= DECAL_H;
}

/** (artnext A7) A door frame's widest wrap: the opening's width plus this (0.1 m jambs a side). */
export const FRAME_WRAP = 0.2;

/** (artnext A7) The door's opening as a thin plan rect along its closed leaf (a leg through the door crosses it). */
function doorOpening(d: Door): PlanRect {
  const l = doorLine(d);
  return planRect(l.cx, l.cz, d.width / 2, 0.05, Math.atan2(-(l.bz - l.az), l.bx - l.ax));
}

/**
 * (artnext A7) The door a frame piece wraps, or null: a visual placement of a `cat.frame` piece whose local x runs along a
 * door's opening, whose hull spans the opening (its width to its width + `FRAME_WRAP`, the opening wholly inside), stands
 * on the door's floor (5 cm) and reaches the door's head.
 */
export function frameDoor(ctx: DressContext, cat: PropCatalogue, p: ArtPlacement): Door | null {
  if (p.cls !== 'visual' || !cat.frame?.includes(p.prop)) return null;
  const h = pieceHull(cat, p.prop);
  const sx = p.s?.[0] ?? 1;
  const sy = p.s?.[1] ?? 1;
  const span = (h.hi[0] - h.lo[0]) * sx;
  const y0 = p.y + Math.min(h.lo[1], h.hi[1]) * sy;
  const y1 = p.y + Math.max(h.lo[1], h.hi[1]) * sy;
  const [cx, , cz] = artToWorld(p, (h.lo[0] + h.hi[0]) / 2, 0, (h.lo[2] + h.hi[2]) / 2);
  const ux = Math.cos(p.yaw);
  const uz = -Math.sin(p.yaw);
  const hz = (Math.abs(h.hi[2] - h.lo[2]) * (p.s?.[2] ?? 1)) / 2;
  for (const d of ctx.doors) {
    const tx = Math.sin(d.yaw);
    const tz = Math.cos(d.yaw);
    if (Math.abs(ux * tx + uz * tz) < 1 - 1e-3) continue;
    if (span < d.width - 1e-3 || span > d.width + FRAME_WRAP + 1e-3) continue;
    if (Math.abs(y0 - d.hinge.y) > 0.05 || y1 < d.hinge.y + d.height - 1e-3) continue;
    const l = doorLine(d);
    const along = (l.cx - cx) * ux + (l.cz - cz) * uz;
    const across = (l.cx - cx) * -uz + (l.cz - cz) * ux;
    if (Math.abs(along) > (span - d.width) / 2 + 1e-3 || Math.abs(across) > hz + 1e-3) continue;
    return d;
  }
  return null;
}

/** (artnext A7) A frame's drawn shapes round its door: the two jambs and the head over the opening (its hull less the opening). */
function frameShapes(cat: PropCatalogue, p: ArtPlacement, d: Door): Shape[] {
  const w = hullObb(cat, p);
  const ux = Math.cos(p.yaw);
  const uz = -Math.sin(p.yaw);
  const l = doorLine(d);
  const o = (l.cx - w.cx) * ux + (l.cz - w.cz) * uz;
  const o0 = o - d.width / 2;
  const o1 = o + d.width / 2;
  const top = d.hinge.y + d.height;
  const out: Shape[] = [];
  const part = (a: number, b: number, y0: number, y1: number): void => {
    if (b - a < 1e-3 || y1 - y0 < 1e-3) return;
    const m = (a + b) / 2;
    out.push(fromWorldObb({ cx: w.cx + ux * m, cz: w.cz + uz * m, hx: (b - a) / 2, hz: w.hz, yaw: w.yaw, y0, y1 }));
  };
  part(-w.hx, o0, w.y0, w.y1);
  part(o1, w.hx, w.y0, w.y1);
  part(o0, o1, Math.max(top, w.y0), w.y1);
  return out;
}

/** (artpol, art-kit P2) A raised piece with no wall behind it hangs (ceiling rules) only from this height over its floor. */
export const MOUNT_CEIL = 1.9;
/** (artpol, polish2 1) How far (m) along a K8 ray a skin's hull may be entered before its own greybox piece and still
 *  count as the piece (a skin proud of its face). */
export const SKIN_RAY_SLACK = 0.02;
/** (artpol, polish2 2) A listed overhang part's (a 2 cm rod's) clearance (m) from a laser beam, from its surface. */
export const SKIN_PART_CLEAR = 0.05;
/** Distance from a point to the 3D segment a -> b. */
function pointSeg3(x: number, y: number, z: number, ax: number, ay: number, az: number, bx: number, by: number, bz: number): number {
  const dx = bx - ax;
  const dy = by - ay;
  const dz = bz - az;
  const l2 = dx * dx + dy * dy + dz * dz;
  const t = l2 < 1e-12 ? 0 : Math.max(0, Math.min(1, ((x - ax) * dx + (y - ay) * dy + (z - az) * dz) / l2));
  return hyp3(x - (ax + dx * t), y - (ay + dy * t), z - (az + dz * t));
}
const overlapY = (a0: number, a1: number, b0: number, b1: number): boolean => a0 < b1 && b0 < a1;
const minDistToShape = (s: Shape, pts: readonly number[]): number => {
  let d = Infinity;
  for (let i = 0; i < pts.length; i += 3) d = Math.min(d, pointObbDist(s.obb, pts[i]!, pts[i + 1]!, pts[i + 2]!));
  return d;
};

/**
 * (ART-KIT L13) Where a placement is mounted, by its geometry (the planner and the checks agree): a ceiling piece by its
 * frame; a piece whose back is on a wall (0.06) that is raised off the floor, or a flush visual (0.2 deep), on the wall;
 * a raised piece with no wall behind it hangs (ceiling rules); everything standing on the floor is a floor prop.
 */
export function placementMount(k: Keepouts, ctx: DressContext, cat: PropCatalogue, p: ArtPlacement): Mount {
  if (mountOf(cat, p.prop) === 'ceiling') return 'ceiling';
  const h = pieceHull(cat, p.prop);
  const sy = p.s?.[1] ?? 1;
  const bottom = p.y + Math.min(h.lo[1], h.hi[1]) * sy;
  const floor = floorUnder(k, ctx.boxes, cat, p);
  const raised = bottom > floor + 0.05;
  const depth = Math.abs(h.hi[2] - h.lo[2]) * (p.s?.[2] ?? 1);
  const onWall = backGap(k, ctx.boxes, cat, p).gap <= 0.06;
  if (onWall && (raised || (p.cls === 'visual' && depth <= 0.2))) return 'wall';
  // (artpol, art-kit P2) only a piece hung clear of head height (bottom 1.9 over the floor) takes the ceiling rules: one
  // raised to body height with no wall behind it is a floor prop (K1-K6, C, K7 rules 2 / 3 and K12 apply)
  if (raised && !onWall && bottom >= floor + MOUNT_CEIL) return 'ceiling';
  return 'floor-free';
}

/** Pieces that hang over a solid run (rule V counts them flush when their back is on a wall; ART-KIT L6). */
export const OVER_RUN: readonly string[] = ['wallCupboards'];
/** Wall pieces that go over a door (K3's wall rule exempts them). */
const OVER_DOOR: readonly string[] = ['exitSign', 'signPlate'];

/**
 * The first keepout one placement breaks (null: none): 'S' (a skin that does not fit its greybox piece), 'V' (rule V),
 * then K1..K13 by mount (ART-PLAN 4.3). Skins are checked by the skin rule alone (they write nothing).
 */
export function blocked(k: Keepouts, ctx: DressContext, cat: PropCatalogue, p: ArtPlacement, mount: Mount): string | null {
  if (p.cls === 'skin' || p.cls === 'skin-hide') {
    const piece = p.skinCyl !== undefined ? ctx.cylinders?.[p.skinCyl] : p.skinOf !== undefined ? ctx.boxes[p.skinOf] : undefined;
    if (!piece) return `S: ${p.prop} skins no greybox piece`;
    const e = skinFit(cat, p, p.skinPart && 's' in piece ? boxSlice(piece, p, p.skinPart[0], p.skinPart[1]) : piece);
    if (e) return `S: ${e}`;
    // (artnext A2) a face skin stands proud of its box's face: the wall-mounted visual rules below (K3 door edges, K4,
    // K7, K12 glass, K8, K9-K11 at wall radii); rule V and the floor rules do not apply (it is the box's face)
    if (p.skinFace === undefined) return null;
    mount = 'wall';
  }
  // (artnext A7) a door frame: its jambs and head stand in for its hull, and the door it wraps passes it
  const fd = frameDoor(ctx, cat, p);
  const shapes = fd ? frameShapes(cat, p, fd) : shapesOf(cat, p);
  // (artnext A6) a floor decal does not keep the floor rules (K1-K6, K13): it is walked over
  const decal = (mount === 'floor-wall' || mount === 'floor-free') && isDecal(k, ctx.boxes, cat, p);
  const opening = fd ? doorOpening(fd) : null;
  /** Is this keepout one the frame's door passes (its K3 / K13 shapes, a K1 / K2 leg through its opening)? */
  const framePass = (rule: string, door: number | undefined, ax: number, az: number, bx: number, bz: number): boolean => {
    if (!fd || !opening) return false;
    if (rule === 'K3' || rule === 'K13') return door === fd.id;
    return (rule === 'K1' || rule === 'K2') && segRectDist(opening, ax, az, bx, bz) <= 0;
  };
  if (p.cls === 'visual' && !fd) {
    const bg = backGap(k, ctx.boxes, cat, p);
    // rule V's wall distance is to the piece's local z = 0 (its back face sits at `back` <= 0)
    const wallDist = OVER_RUN.includes(p.prop) && bg.gap <= 0.15 ? -1 : bg.gap - bg.back;
    const e = ruleV(cat, p, floorUnder(k, ctx.boxes, cat, p), wallDist);
    if (e) return `V: ${e}`;
  }
  const floor = mount === 'floor-wall' || mount === 'floor-free';
  if (floor) {
    // (ART-KIT L12) a box keeps the nav agent's clearance more off K1-K6 / K13, so the walkable cells inside them stay walkable (ART-PLAN 4.4 item 2)
    const navPad = (s: Shape, rule: string): number => (s.box && NAV_RULES.includes(rule) ? KEEP.navClear : 0);
    for (const c of k.caps) {
      if (decal && NAV_RULES.includes(c.rule)) continue;
      if (framePass(c.rule, c.door, c.ax, c.az, c.bx, c.bz)) continue;
      for (const s of shapes) {
        if (!overlapY(s.y0, s.y1, c.y0, c.y1)) continue;
        const r = c.r + navPad(s, c.rule);
        // (artpol, load time) the rect's circumcircle clear of the leg by r: the rect is too (most legs, cheaply)
        if (pointSegDist(s.plan.cx, s.plan.cz, c.ax, c.az, c.bx, c.bz) - hyp2(s.plan.hx, s.plan.hz) > r + 1e-4) continue;
        if (segRectDist(s.plan, c.ax, c.az, c.bx, c.bz) < r - 1e-6) return `${c.rule}: ${p.prop} within ${r.toFixed(2)} of ${c.what}`;
      }
    }
    for (const z of k.zones) {
      if (decal && NAV_RULES.includes(z.rule)) continue;
      if (fd && (z.rule === 'K3' || z.rule === 'K13') && z.door === fd.id) continue;
      for (const s of shapes) {
        if (!overlapY(s.y0, s.y1, z.y0, z.y1)) continue;
        const pad = navPad(s, z.rule);
        if (pad > 0 ? rectGap(s.plan, z.r) < pad - 1e-6 : rectsOverlap(s.plan, z.r, 0)) return `${z.rule}: ${p.prop} in ${z.what}`;
      }
    }
    // (ART-KIT L12) cover (ART-PLAN 4.4 item 4): a visible box tall enough to make cover stays 3.0 off route and patrol legs
    for (const s of shapes) {
      if (!s.solid || !classifyHeight(s.y1 - s.y0) || Math.max(s.plan.hx, s.plan.hz) * 2 < MIN_FACE) continue;
      for (const c of k.caps) {
        if ((c.rule !== 'K1' && c.rule !== 'K2') || !overlapY(s.y0, s.y0 + 0.5, c.y0, c.y1)) continue;
        if (pointSegDist(s.plan.cx, s.plan.cz, c.ax, c.az, c.bx, c.bz) - hyp2(s.plan.hx, s.plan.hz) > KEEP.cover + 1e-4) continue;
        if (segRectDist(s.plan, c.ax, c.az, c.bx, c.bz) < KEEP.cover - 1e-6) return `C: ${p.prop} makes cover within ${KEEP.cover} of ${c.what}`;
      }
    }
    // K7 lips: rule 2 (a box with top >= 1.2 over the booster's floor within 4.0), rule 3 (a box 0.6-1.7 tall within 1.0
    // of the wall under the lip), the headroom prism
    for (const l of k.lips) {
      for (const s of shapes) {
        const d = segRectDist(s.plan, l.ax, l.az, l.bx, l.bz);
        const top = s.y1 - l.floor;
        if (s.box && top >= KEEP.lipTop && s.y0 < l.y && d < KEEP.lipReach) return `K7: ${p.prop} a ${top.toFixed(2)} m box within ${KEEP.lipReach} of lip ${l.id} (rule 2)`;
        if (s.box && top >= KEEP.lipWallBand[0] && top <= KEEP.lipWallBand[1] && d < KEEP.lipWall) return `K7: ${p.prop} a step under lip ${l.id} (rule 3)`;
        if (overlapY(s.y0, s.y1, l.prism.y0, l.prism.y1) && rectsOverlap(s.plan, l.prism.r, 0)) return `K7: ${p.prop} in ${l.prism.what}`;
      }
    }
    for (const gi of k.glass) {
      const g = boxPlan(ctx.boxes[gi]!);
      for (const s of shapes) if (overlapY(s.y0, s.y1, g.y0, g.y1) && rectGap(s.plan, g.r) < KEEP.glass - 1e-6) return `K12: ${p.prop} within ${KEEP.glass} of glass box ${gi}`;
    }
  } else if (mount === 'wall') {
    if (!OVER_DOOR.includes(p.prop)) {
      for (const z of k.wallZones) {
        if (fd && z.door === fd.id) continue;
        for (const s of shapes) if (overlapY(s.y0, s.y1, z.y0, z.y1) && rectsOverlap(s.plan, z.r, 0)) return `K3: ${p.prop} within ${KEEP.doorWall} of ${z.what}`;
      }
    }
    for (const w of k.wallPts) for (const s of shapes) if (pointObbDist(s.obb, w.x, w.y, w.z) < w.r) return `K4: ${p.prop} within ${w.r} of ${w.what}`;
    for (const l of k.lips) {
      for (const s of shapes) if (s.y0 < l.y + 0.1 && segRectDist(s.plan, l.ax, l.az, l.bx, l.bz) < 0.4) return `K7: ${p.prop} on the wall under lip ${l.id}`;
    }
    const bg = backGap(k, ctx.boxes, cat, p);
    if (bg.glass) return `K12: ${p.prop} mounted on glass`;
    if (bg.gap > 0.06) return `W: ${p.prop} has no wall behind it`;
  } else {
    for (const l of k.lips) for (const s of shapes) if (overlapY(s.y0, s.y1, l.prism.y0, l.prism.y1) && rectsOverlap(s.plan, l.prism.r, 0)) return `K7: ${p.prop} in ${l.prism.what}`;
  }
  // K8 camera rays: new boxes, and visual pieces over 0.35 in any axis
  const cams = shapes.filter((s) => (s.box ? true : p.cls === 'visual' && Math.max(s.obb.h[0], s.obb.h[1], s.obb.h[2]) * 2 > KEEP.camVisual));
  if (cams.length) {
    for (const s of cams) {
      const lo = [s.plan.cx - s.plan.hx - s.plan.hz, s.y0, s.plan.cz - s.plan.hx - s.plan.hz];
      const hi = [s.plan.cx + s.plan.hx + s.plan.hz, s.y1, s.plan.cz + s.plan.hx + s.plan.hz];
      for (const r of k.rays) {
        if (r.hi[0] < lo[0]! || r.lo[0] > hi[0]! || r.hi[1] < lo[1]! || r.lo[1] > hi[1]! || r.hi[2] < lo[2]! || r.lo[2] > hi[2]!) continue;
        if (segHitsObb(s.obb, r.ax, r.ay, r.az, r.bx, r.by, r.bz, 0.005)) return `K8: ${p.prop} blocks camera ${r.cam} towards (${r.bx.toFixed(1)}, ${r.by.toFixed(1)}, ${r.bz.toFixed(1)})`;
      }
    }
  }
  // K9 / K10 / K11 tubes and spheres
  // (artpol, load time) a tube whose bounds are r or more off a shape's bounds on any axis is clear of it
  const sbb = shapes.map((s) => obbAabb(s.obb));
  for (const t of k.tubes) {
    const r = floor ? t.floor : mount === 'wall' ? t.wall : t.ceil;
    for (let si = 0; si < shapes.length; si++) {
      const b = sbb[si]!;
      if (t.bb[0] - b[3] >= r || b[0] - t.bb[3] >= r || t.bb[1] - b[4] >= r || b[1] - t.bb[4] >= r || t.bb[2] - b[5] >= r || b[2] - t.bb[5] >= r) continue;
      if (minDistToShape(shapes[si]!, t.pts) < r - 1e-6) return `${t.rule}: ${p.prop} within ${r} of ${t.what}`;
    }
  }
  return null;
}

/** (ART-KIT L14) Does a floor piece stand on a floor: its hull's bottom on a collide box top (3 cm) under its origin and
 *  under each footprint corner (5 cm in)? */
export function standsOn(k: Keepouts, boxes: readonly BoxPiece[], cat: PropCatalogue, p: ArtPlacement): boolean {
  const h = pieceHull(cat, p.prop);
  const bottom = p.y + Math.min(h.lo[1], h.hi[1]) * (p.s?.[1] ?? 1);
  const sx = p.s?.[0] ?? 1;
  const sz = p.s?.[2] ?? 1;
  const pts: [number, number][] = [[0, 0]];
  for (const [a, b] of [[h.lo[0], h.lo[2]], [h.hi[0], h.lo[2]], [h.hi[0], h.hi[2]], [h.lo[0], h.hi[2]]] as const) pts.push([(a + Math.sign(-a) * 0.05) * sx, (b + Math.sign(-b) * 0.05) * sz]);
  const c = Math.cos(p.yaw);
  const s = Math.sin(p.yaw);
  for (const [lx, lz] of pts) {
    const x = p.x + lx * c + lz * s;
    const z = p.z - lx * s + lz * c;
    let top = -Infinity;
    for (const i of k.grid.query(x, z, x, z)) {
      const b = boxes[i]!;
      if (!b.collide || pointRectDist(boxPlan(b).r, x, z) > 0) continue;
      const t = boxPlan(b).y1;
      if (t <= bottom + 0.3 && t > top) top = t;
    }
    if (Math.abs(top - bottom) > 0.03) return false;
  }
  return true;
}

/** Does a placement's footprint overlap a greybox box (other than the floor it stands on and the wall it hangs on)? */
export function overlapsGreybox(k: Keepouts, boxes: readonly BoxPiece[], cat: PropCatalogue, p: ArtPlacement): number {
  // (artnext A6) a floor decal lies on the floor and under whatever stands on it
  if (isDecal(k, boxes, cat, p)) return -1;
  const shapes = shapesOf(cat, p);
  for (const s of shapes) {
    const e = Math.abs(s.plan.ux) * s.plan.hx + Math.abs(s.plan.uz) * s.plan.hz;
    const f = Math.abs(s.plan.uz) * s.plan.hx + Math.abs(s.plan.ux) * s.plan.hz;
    for (const i of k.grid.query(s.plan.cx - e, s.plan.cz - f, s.plan.cx + e, s.plan.cz + f)) {
      const b = boxes[i]!;
      if (!b.collide && b.visible === false) continue;
      const g = boxPlan(b);
      if (g.y1 <= s.y0 + 0.01 || g.y0 >= s.y1 - 0.01) continue;
      if (rectsOverlap(s.plan, g.r, 0.01)) return i;
    }
  }
  return -1;
}

/**
 * (polish2, art-check P3) A skin with a listed overhang (`cat.overhang`: hanger rods, an exhaust stack, chimney pots)
 * draws past its greybox piece, which the K8 camera rays and the K9 laser tubes were never measured against: its hull
 * must not cross a camera ray (K8) nor come within `KEEP.laser` of a laser (K9). Skins flush on their piece are the
 * greybox itself and are not checked. The hull is a box, so what the greybox piece already decides is left out: a ray
 * that touches the piece itself (a floor point on the counter's face), and laser points over the piece's own plan
 * footprint (las-tray runs across the S4 cage basket's walk surface by design; the hanger rods stand at the basket's
 * edges). Null: clear.
 */
export function skinReach(k: Keepouts, ctx: DressContext, cat: PropCatalogue, p: ArtPlacement): string | null {
  if (!cat.overhang[p.prop]) return null;
  const s = fromWorldObb(hullObb(cat, p));
  const box = p.skinOf !== undefined ? ctx.boxes[p.skinOf] : undefined;
  const cyl = p.skinCyl !== undefined ? ctx.cylinders?.[p.skinCyl] : undefined;
  const own = box ? boxObb(box) : cyl ? obbOf(cyl.c, [cyl.r * 2, cyl.h, cyl.r * 2], 0) : null;
  const ownPlan = box ? boxPlan(box).r : null;
  const lo0 = s.plan.cx - s.plan.hx - s.plan.hz;
  const hi0 = s.plan.cx + s.plan.hx + s.plan.hz;
  const lo2 = s.plan.cz - s.plan.hx - s.plan.hz;
  const hi2 = s.plan.cz + s.plan.hx + s.plan.hz;
  for (const r of k.rays) {
    if (r.hi[0] < lo0 || r.lo[0] > hi0 || r.hi[1] < s.y0 || r.lo[1] > s.y1 || r.hi[2] < lo2 || r.lo[2] > hi2) continue;
    const tHull = segEntryObb(s.obb, r.ax, r.ay, r.az, r.bx, r.by, r.bz, 0.005);
    if (tHull < 0) continue;
    // (artpol, polish2 1) the piece decides the ray only from where the ray meets it: skipped when the hull is entered
    // no more than SKIN_RAY_SLACK before the piece (a skin proud of its face), not when an overhang crosses it first
    const tOwn = own ? segEntryObb(own, r.ax, r.ay, r.az, r.bx, r.by, r.bz, 0) : -1;
    if (tOwn >= 0 && (tOwn - tHull) * hyp3(r.bx - r.ax, r.by - r.ay, r.bz - r.az) <= SKIN_RAY_SLACK) continue;
    return `K8: skin ${p.prop} blocks camera ${r.cam} towards (${r.bx.toFixed(1)}, ${r.by.toFixed(1)}, ${r.bz.toFixed(1)})`;
  }
  // (artpol, polish2 2) the piece's own height band (its box or cylinder, KEEP.laser round): a laser point over its plan
  // footprint but above or below that band meets the overhang alone, and is checked
  const band0 = (box ? boxPlan(box).y0 : cyl ? cyl.c[1] - cyl.h / 2 : 0) - KEEP.laser;
  const band1 = (box ? boxPlan(box).y1 : cyl ? cyl.c[1] + cyl.h / 2 : 0) + KEEP.laser;
  // an overhang that lists its real parts (rods, a stack) is measured by them out of the band, not by its hull box
  const parts = cat.overhang[p.prop]!.parts;
  const wp: number[] = [];
  const grow = Math.max(p.s?.[0] ?? 1, p.s?.[2] ?? 1);
  for (const q of parts ?? []) wp.push(...artToWorld(p, q.a[0], q.a[1], q.a[2]), ...artToWorld(p, q.b[0], q.b[1], q.b[2]), q.r * grow);
  for (const t of k.tubes) {
    if (t.rule !== 'K9') continue;
    for (let i = 0; i + 2 < t.pts.length; i += 3) {
      const x = t.pts[i]!;
      const y = t.pts[i + 1]!;
      const z = t.pts[i + 2]!;
      const inBand = y >= band0 && y <= band1;
      if (inBand && (ownPlan ? pointRectDist(ownPlan, x, z) <= 0 : cyl ? hyp2(x - cyl.c[0], z - cyl.c[2]) <= cyl.r : false)) continue;
      if (parts && !inBand) {
        for (let j = 0; j < wp.length; j += 7) {
          if (pointSeg3(x, y, z, wp[j]!, wp[j + 1]!, wp[j + 2]!, wp[j + 3]!, wp[j + 4]!, wp[j + 5]!) - wp[j + 6]! < SKIN_PART_CLEAR - 1e-6) return `K9: skin ${p.prop} (a listed part) within ${SKIN_PART_CLEAR} of ${t.what}`;
        }
        continue;
      }
      if (pointObbDist(s.obb, x, y, z) < KEEP.laser - 1e-6) return `K9: skin ${p.prop} within ${KEEP.laser} of ${t.what}`;
    }
  }
  return null;
}

/** Every violation of a placement list (empty: clean): each placement's `blocked`, overlaps with greybox boxes ('B',
 *  skins excepted) and between two placements' boxes ('B'). */
export function checkDressing(ctx: DressContext, cats: CatalogueSet, ps: readonly ArtPlacement[]): string[] {
  const k = buildKeepouts(ctx);
  const out: string[] = [];
  const shapes: (Shape[] | null)[] = [];
  ps.forEach((p, i) => {
    const cat = cats[p.cat];
    if (!cat) {
      out.push(`#${i} ${p.cat}:${p.prop}: no catalogue`);
      shapes.push(null);
      return;
    }
    const m = placementMount(k, ctx, cat, p);
    const e = blocked(k, ctx, cat, p, m);
    if (e) out.push(`#${i} ${p.cat}:${p.prop} (${p.x.toFixed(2)}, ${p.y.toFixed(2)}, ${p.z.toFixed(2)}): ${e}`);
    if (p.cls === 'skin' || p.cls === 'skin-hide') {
      const r = e ? null : skinReach(k, ctx, cat, p);
      if (r) out.push(`#${i} ${p.cat}:${p.prop} (${p.x.toFixed(2)}, ${p.y.toFixed(2)}, ${p.z.toFixed(2)}): ${r}`);
      shapes.push(null);
      return;
    }
    if ((m === 'floor-wall' || m === 'floor-free') && !frameDoor(ctx, cat, p)) {
      const g = overlapsGreybox(k, ctx.boxes, cat, p);
      if (g >= 0) out.push(`#${i} ${p.cat}:${p.prop}: B: overlaps greybox box ${g}`);
    }
    shapes.push(writesBoxes(p) ? shapesOf(cat, p).filter((s) => s.box) : null);
  });
  for (let i = 0; i < ps.length; i++) {
    const a = shapes[i];
    if (!a?.length) continue;
    for (let j = i + 1; j < ps.length; j++) {
      const b = shapes[j];
      if (!b?.length) continue;
      let hit = false;
      for (const x of a) for (const y of b) if (overlapY(x.y0 + 0.01, x.y1 - 0.01, y.y0, y.y1) && rectsOverlap(x.plan, y.plan, 0.01)) hit = true;
      if (hit) out.push(`#${i} ${ps[i]!.prop} and #${j} ${ps[j]!.prop}: B: boxes overlap`);
    }
  }
  return out;
}

