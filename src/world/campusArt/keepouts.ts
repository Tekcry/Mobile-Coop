const CELL = 2;
export class BoxGrid {
  private cells = new Map<number, number[]>();
  private readonly stamp: Int32Array;
  private tick = 0;
  constructor(
    boxes: readonly BoxPiece[],
    n: number,
    readonly x0: number,
    readonly z0: number,
    readonly x1: number,
    readonly z1: number,
  ) {
    this.stamp = new Int32Array(n);
    for (let i = 0; i < n; i++) {
      const p = boxPlan(boxes[i]!);
      const e = Math.abs(p.r.ux) * p.r.hx + Math.abs(p.r.uz) * p.r.hz;
      const f = Math.abs(p.r.uz) * p.r.hx + Math.abs(p.r.ux) * p.r.hz;
      const bx0 = p.r.cx - e;
      const bx1 = p.r.cx + e;
      const bz0 = p.r.cz - f;
      const bz1 = p.r.cz + f;
      if (bx1 < x0 || bx0 > x1 || bz1 < z0 || bz0 > z1) continue;
      for (let i0 = this.ci(Math.max(bx0, x0)); i0 <= this.ci(Math.min(bx1, x1)); i0++) {
        for (let k0 = this.ck(Math.max(bz0, z0)); k0 <= this.ck(Math.min(bz1, z1)); k0++) {
          const key = i0 * 4096 + k0;
          let c = this.cells.get(key);
          if (!c) this.cells.set(key, (c = []));
          c.push(i);
        }
      }
    }
  }
  private ci(x: number): number {
    return Math.floor((x - this.x0) / CELL);
  }
  private ck(z: number): number {
    return Math.floor((z - this.z0) / CELL);
  }
  /** Box indices whose plan bounds may meet x0..x1, z0..z1 (sorted, unique). */
  query(x0: number, z0: number, x1: number, z1: number): number[] {
    // (artpol, load time) de-duplicated by a per-query stamp, not a Set
    const out: number[] = [];
    const t = ++this.tick;
    for (let i = this.ci(Math.max(x0, this.x0)); i <= this.ci(Math.min(x1, this.x1)); i++) {
      for (let k = this.ck(Math.max(z0, this.z0)); k <= this.ck(Math.min(z1, this.z1)); k++) {
        const c = this.cells.get(i * 4096 + k);
        if (!c) continue;
        for (let n = 0; n < c.length; n++) {
          const j = c[n]!;
          if (this.stamp[j] === t) continue;
          this.stamp[j] = t;
          out.push(j);
        }
      }
    }
    if (out.length > 1) out.sort((a, b) => a - b);
    return out;
  }
}

