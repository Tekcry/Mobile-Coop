// noticed within about 6 m inside a guard's focus cone, filling slower than in bright light. Runs the bots and the Area 1 windows
// with the engine's sightRate and with the proposal, on Dead Line v2 Area 1, the D1 campus (map-dead-line.json) and the Trunk Annex.
// Writes map-dead-line-v2-perception.md. Run: node docs/design/map-dead-line-v2-perception.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { makeCtx } from './map-dead-line-sim.mjs';
import { sprintBot, timetableBot } from './map-dead-line-bots.mjs';
import { DIM_NEAR, proposedRate } from './map-dead-line-v2-dimnear.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const f1 = (n) => (n === null || n === undefined ? '-' : (Math.round(n * 10) / 10).toFixed(1));
const pc = (n) => `${Math.round(n * 100)}%`;

// the Trunk Annex keeps its routes as hops; the bots want key points
function annexToCtxJson(A) {
  const D = JSON.parse(JSON.stringify(A));
  // the Annex render script places G4 on the upper floor and G6 on the roof (guardLevel in map-trunk-annex-render.mjs)
  for (const g of D.guards) { g.ch = [1]; g.level = g.id === 'G4' ? 'U' : g.id === 'G6' ? 'R' : 'G'; }
  const hops = (id) => A.routes.find((r) => r.id === id).hops;
  const pts = [];
  const push = (hs) => {
    for (const h of hs) {
      if (h.link) { const e = h.pts[h.pts.length - 1]; pts.push({ lv: e[0], x: e[1], z: e[2], via: h.link, m: 'walk' }); continue; }
      for (const p of h.pts) { const last = pts[pts.length - 1]; if (last && last.lv === p[0] && last.x === p[1] && last.z === p[2]) continue; pts.push({ lv: p[0], x: p[1], z: p[2], m: h.m === 'crawl' ? 'crawl' : 'walk' }); }
    }
  };
  push(hops('O1-A'));
  pts[0].chapter = 1;
  const o1 = A.objectives.find((o) => o.id === 'O1'), o2 = A.objectives.find((o) => o.id === 'O2');
  pts[pts.length - 1].hold = o1.hold ?? 3;
  push(hops('O2-A').map((h, k) => (k === 0 ? { ...h, pts: h.pts.slice(1) } : h)));
  pts[pts.length - 1].hold = o2.hold ?? 4;
  push(hops('EX-1').map((h, k) => (k === 0 ? { ...h, pts: h.pts.slice(1) } : h)));
  D.routes = [{ id: 'M', name: 'Main run (O1-A, O2-A, EX-1)', kind: 'main', pts }];
  return D;
}

function runBots(D, label, routes = ['M']) {
  const out = {};
  for (const mode of ['engine', 'proposal']) {
    const ctx = makeCtx(D);
    if (mode === 'proposal') ctx.sightRateFn = proposedRate;
    const sp = sprintBot(ctx);
    const tt = {};
    for (const r of routes) tt[r] = timetableBot(ctx, { route: r });
    out[mode] = { sp, tt };
  }
  return { label, out };
}

const results = [];
// Area 1 (Dead Line v2): the routes and the windows come from the Area 1 analysis with the override; here the bots
const V2 = JSON.parse(fs.readFileSync(path.join(here, 'map-dead-line-v2.json'), 'utf8'));
results.push(runBots(V2, 'Dead Line v2 Area 1', ['M', 'UP', 'UPQ', 'BELOW']));
const OLD = JSON.parse(fs.readFileSync(path.join(here, 'map-dead-line.json'), 'utf8'));
results.push(runBots(OLD, 'Dead Line D1 campus (old layout)'));
const AN = annexToCtxJson(JSON.parse(fs.readFileSync(path.join(here, 'map-trunk-annex.json'), 'utf8')));
const anCtx = makeCtx(AN);
const anErr = anCtx.routes.M.error;
if (!anErr) results.push(runBots(AN, 'Trunk Annex (O1-A, O2-A, EX-1)'));

// Area 1 windows on the ground route with the proposal (crossing at crouch gear 4, every 0.5 s start, peak meter under 0.3)
const { execFileSync } = await import('node:child_process');
const winTable = (json) => JSON.parse(json);
let win;
try {
  const r = execFileSync(process.execPath, [path.join(here, 'map-dead-line-v2-analysis.mjs'), '--fast', '--proposal', '--json-only'], { encoding: 'utf8' });
  win = winTable(r.slice(r.indexOf('{')));
} catch (e) { win = { error: e.message.split('\n')[0] }; }

const L = [];
const P = (s = '') => L.push(s);
P('# Proposed perception change: measured, not applied');
P();
P(`Generated by \`map-dead-line-v2-perception.mjs\` (${new Date().toISOString().slice(0, 10)}). The engine (\`src/ai/perception.ts\`) is unchanged.`);
P();
P('**Proposal.** Inside the focus cone and within 8 m, a target in dim light gets a second fill rate that does not use the squared light factor:');
P(`\`dim = ${DIM_NEAR.rate} x (1 - d / ${DIM_NEAR.range}) x k x stance x motion x exposure\`, where k rises from 0 at light ${DIM_NEAR.from} to 1 at ${DIM_NEAR.full} (darkness below 0.2 is untouched). The guard uses the larger of this and the normal rate. For a crouched player moving at 1.8 m/s in light 0.28 this is 0.99/s at 0 m, 0.50/s at 4 m and 0.25/s at 6 m (just above the 0.2/s leak: noticed within about 6 m); in bright light (0.6) the normal rate at 6 m is 0.80/s, so dim still fills slower. It would go in \`PERCEPTION\` as a config block (\`dimNear: { from, full, range, rate }\`, \`rate: 0\` = off).`);
P();
P('| Map | Bot | Engine today | With the proposal |');
P('| --- | --- | --- | --- |');
for (const r of results) {
  const e = r.out.engine, p = r.out.proposal;
  P(`| ${r.label} | Sprint bot | alarm ${f1(e.sp.alarmAtS)} s, ${e.sp.spotted.length} spotted, ${e.sp.heard.length} heard | alarm ${f1(p.sp.alarmAtS)} s, ${p.sp.spotted.length} spotted, ${p.sp.heard.length} heard |`);
  for (const id of Object.keys(e.tt)) {
    const a = e.tt[id], b = p.tt[id];
    const s = (t) => `${t.reached ? 'reached' : 'NOT reached'}, ${f1(t.finishedAtS)} s (${f1(t.finishedAtS / 60)} min), waited ${pc(t.waitShare)}, max meter ${t.maxMeter.toFixed(2)}, ${t.unsafeMoments} unsafe moments`;
    P(`| ${r.label} | Timetable bot ${id} | ${s(a)} | ${s(b)} |`);
  }
}
if (anErr) P(`| Trunk Annex | - | route conversion failed: ${anErr} | |`);
P();
if (win && !win.error) {
  P('Area 1 encounter windows, ground route (safe share of start times):');
  P();
  P('| Encounter | Engine today | With the proposal |');
  P('| --- | --- | --- |');
  for (const e of Object.keys(win.engine)) P(`| ${e} | ${pc(win.engine[e])} | ${pc(win.proposal[e])} |`);
  P();
}
P('**Decision.** Not applied: Area 1 meets every pacing and window target (items 2 and 3) with map changes alone (see `map-dead-line-v2-validation.md`). The numbers above are for Michael to decide on the whole-game change later.');
